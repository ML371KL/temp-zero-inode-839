/**
 * Всё остальное под `/data/` — честный 404, а не страница.
 *
 * Это закрытие класса, а не частного случая. Cloudflare Pages на путь, для которого не
 * нашлось ни функции, ни файла, отвечает **200 и HTML главной страницы**. Для браузера
 * это удобно, для программы — ложь: она просила данные, получила «успех» и разбирает
 * вёрстку как JSON.
 *
 * Дважды за двое суток это стоило дорого. Сначала агент котировок пошёл за правилами
 * алертов на `/data/alerts.enc`, где функции ещё не было, получил 200 с версткой,
 * упал на разборе — и движок алертов девять часов не проверял ни одного правила при
 * зелёных прогонах. Потом сторож свежести спросил Last-Modified методом HEAD, получил
 * ту же заглушку и объявил три живые панели мёртвыми.
 *
 * Конкретные функции рядом (`portfolio.enc`, `quotes.enc`, `alerts.enc`) имеют
 * приоритет над этим перехватом: Pages выбирает более точный маршрут. Сюда попадает
 * только то, чего действительно нет, — опечатка в адресе, забытая функция, объект,
 * который переименовали и не заметили. И теперь про это сразу видно, что его нет.
 */

const NOT_FOUND = JSON.stringify({
  error: "no such data object",
  hint: "под /data/ живут только объекты, у которых есть своя функция",
});

function refuse() {
  return new Response(NOT_FOUND, {
    status: 404,
    headers: {
      "content-type": "application/json; charset=utf-8",
      "cache-control": "no-store",
    },
  });
}

export const onRequest = refuse;
